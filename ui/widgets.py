"""
UI Layer — Small reusable widgets shared across modules.
"""
from __future__ import annotations

from PyQt6.QtCore import Qt, pyqtSignal
from PyQt6.QtWidgets import (
    QButtonGroup,
    QFrame,
    QHBoxLayout,
    QLabel,
    QPlainTextEdit,
    QPushButton,
    QVBoxLayout,
    QWidget,
)

from data.models import SessionStatus
from ui.theme import DARK, FONT_MONO_FALLBACK

_STATUS_TEXT = {
    SessionStatus.PENDING: "Idle",
    SessionStatus.RUNNING: "Running…",
    SessionStatus.COMPLETE: "Complete",
    SessionStatus.FAILED: "Failed",
}

_STATUS_OBJECT_NAME = {
    SessionStatus.PENDING: "statusPending",
    SessionStatus.RUNNING: "statusRunning",
    SessionStatus.COMPLETE: "statusComplete",
    SessionStatus.FAILED: "statusError",
}


class StatusPill(QLabel):
    """A small colored status label reflecting SessionStatus."""

    def __init__(self, parent: QWidget | None = None):
        super().__init__(parent)
        self.set_status(SessionStatus.PENDING)

    def set_status(self, status: SessionStatus, detail: str | None = None) -> None:
        text = _STATUS_TEXT.get(status, str(status))
        if detail:
            text = f"{text} — {detail}"
        self.setText(text)
        self.setObjectName(_STATUS_OBJECT_NAME.get(status, "statusPending"))
        # Re-polish so the new objectName's QSS rule takes effect immediately.
        self.style().unpolish(self)
        self.style().polish(self)


class Card(QFrame):
    """A titled card container used throughout the module panels."""

    def __init__(self, title: str, parent: QWidget | None = None):
        super().__init__(parent)
        self.setObjectName("card")

        self._layout = QVBoxLayout(self)
        self._layout.setContentsMargins(16, 14, 16, 16)
        self._layout.setSpacing(10)

        if title:
            title_label = QLabel(title)
            title_label.setObjectName("cardTitle")
            self._layout.addWidget(title_label)

    def body_layout(self) -> QVBoxLayout:
        return self._layout

    def add_widget(self, widget: QWidget) -> None:
        self._layout.addWidget(widget)


class EmptyState(QWidget):
    """Centered placeholder shown when a module has nothing to display yet."""

    def __init__(self, message: str, parent: QWidget | None = None):
        super().__init__(parent)
        layout = QVBoxLayout(self)
        layout.setAlignment(Qt.AlignmentFlag.AlignCenter)
        label = QLabel(message)
        label.setObjectName("placeholderText")
        label.setAlignment(Qt.AlignmentFlag.AlignCenter)
        label.setWordWrap(True)
        layout.addWidget(label)


class MonoBlock(QPlainTextEdit):
    """Read-only monospace text block for raw protocol output (headers, bodies)."""

    def __init__(self, text: str = "", parent: QWidget | None = None):
        super().__init__(parent)
        self.setPlainText(text)
        self.setReadOnly(True)
        self.setLineWrapMode(QPlainTextEdit.LineWrapMode.WidgetWidth)
        self.setStyleSheet(f"""
            QPlainTextEdit {{
                background-color: {DARK['bg_input']};
                color: {DARK['text_primary']};
                border: 1px solid {DARK['border_subtle']};
                border-radius: 6px;
                font-family: '{FONT_MONO_FALLBACK}';
                font-size: 12px;
                padding: 10px;
            }}
        """)

    def set_text(self, text: str) -> None:
        self.setPlainText(text)


class DataSourceBadge(QLabel):
    """
    A prominent, unambiguous label marking whether the data on screen is a
    real OS-level capture/probe or generated by the simulation engine.
    Used by Packet Explorer and Internet Route Explorer, the first modules
    where this distinction matters — every other module is always real.
    """

    def __init__(self, is_real: bool, parent: QWidget | None = None):
        super().__init__(parent)
        self.set_source(is_real)

    def set_source(self, is_real: bool) -> None:
        if is_real:
            self.setText("● LIVE CAPTURE")
            color = DARK["accent"]
            bg = DARK["accent_bg"]
        else:
            self.setText("◆ SIMULATED DATA")
            color = DARK["accent_blue"]
            bg = DARK["accent_blue_bg"]
        self.setStyleSheet(f"""
            color: {color};
            background-color: {bg};
            border-radius: 4px;
            padding: 4px 10px;
            font-size: 11px;
            font-weight: 700;
            letter-spacing: 0.5px;
        """)


class SegmentedToggle(QWidget):
    """A small pill-style toggle between 2+ named views (e.g. Parsed / Raw)."""

    option_changed = pyqtSignal(str)  # emits the selected option's key

    def __init__(self, options: list[tuple[str, str]], parent: QWidget | None = None):
        """options: list of (key, label) tuples; first is selected by default."""
        super().__init__(parent)
        layout = QHBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)
        layout.setSpacing(4)

        self._group = QButtonGroup(self)
        self._group.setExclusive(True)
        self._buttons: dict[str, QPushButton] = {}

        for i, (key, label) in enumerate(options):
            btn = QPushButton(label)
            btn.setCheckable(True)
            btn.setCursor(Qt.CursorShape.PointingHandCursor)
            btn.setObjectName("segmentBtn")
            btn.setMinimumWidth(btn.fontMetrics().horizontalAdvance(label) + 36)
            if i == 0:
                btn.setChecked(True)
            self._group.addButton(btn)
            self._buttons[key] = btn
            btn.clicked.connect(lambda _checked, k=key: self.option_changed.emit(k))
            layout.addWidget(btn)

        layout.addStretch()

        self.setStyleSheet(f"""
            QPushButton#segmentBtn {{
                background-color: transparent;
                color: {DARK['text_secondary']};
                border: 1px solid {DARK['border']};
                padding: 5px 14px;
                font-size: 11px;
                border-radius: 5px;
            }}
            QPushButton#segmentBtn:checked {{
                background-color: {DARK['accent_bg']};
                color: {DARK['accent']};
                border: 1px solid {DARK['accent_dim']};
                font-weight: 600;
            }}
            QPushButton#segmentBtn:hover:!checked {{
                color: {DARK['text_primary']};
                border: 1px solid {DARK['text_secondary']};
            }}
        """)
